export function icon(name, size = 18) {
  const inner = ICONS[name] || "";
  return `<svg class="icon" aria-hidden="true" viewBox="0 0 24 24" width="${size}" height="${size}" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner}</svg>`;
}

// Replaces every <span data-icon="name"> placeholder in the page (and in
// any element passed in) with the matching inline SVG.
export function hydrateIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((el) => {
    const size = parseInt(el.dataset.iconSize || "18", 10);
    el.innerHTML = icon(el.dataset.icon, size);
    el.removeAttribute("data-icon");
  });
}
